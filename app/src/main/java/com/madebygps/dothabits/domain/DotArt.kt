/** Original 3×5 dot font for digits and a few glyphs (Glyph Matrix + dot-matrix UI accents). */
object DotFont {
    const val W = 3
    const val H = 5

    private val glyphs: Map<Char, String> = mapOf(
        '0' to "###" + "#.#" + "#.#" + "#.#" + "###",
        '1' to ".#." + "##." + ".#." + ".#." + "###",
        '2' to "###" + "..#" + "###" + "#.." + "###",
        '3' to "###" + "..#" + ".##" + "..#" + "###",
        '4' to "#.#" + "#.#" + "###" + "..#" + "..#",
        '5' to "###" + "#.." + "###" + "..#" + "###",
        '6' to "###" + "#.." + "###" + "#.#" + "###",
        '7' to "###" + "..#" + ".#." + ".#." + ".#.",
        '8' to "###" + "#.#" + "###" + "#.#" + "###",
        '9' to "###" + "#.#" + "###" + "..#" + "###",
        '/' to "..#" + "..#" + ".#." + "#.." + "#..",
        ':' to "..." + ".#." + "..." + ".#." + "...",
        '-' to "..." + "..." + "###" + "..." + "...",
        ' ' to "..." + "..." + "..." + "..." + "...",
        'A' to ".#." + "#.#" + "###" + "#.#" + "#.#",
        'D' to "##." + "#.#" + "#.#" + "#.#" + "##.",
        'E' to "###" + "#.." + "##." + "#.." + "###",
        'F' to "###" + "#.." + "##." + "#.." + "#..",
        'H' to "#.#" + "#.#" + "###" + "#.#" + "#.#",
        'I' to "###" + ".#." + ".#." + ".#." + "###",
        'M' to "#.#" + "###" + "###" + "#.#" + "#.#",
        'N' to "##." + "#.#" + "#.#" + "#.#" + "#.#",
        'O' to "###" + "#.#" + "#.#" + "#.#" + "###",
        'R' to "##." + "#.#" + "##." + "#.#" + "#.#",
        'S' to "###" + "#.." + "###" + "..#" + "###",
        'T' to "###" + ".#." + ".#." + ".#." + ".#.",
        'U' to "#.#" + "#.#" + "#.#" + "#.#" + "###",
        'W' to "#.#" + "#.#" + "###" + "###" + "#.#",
        'P' to "###" + "#.#" + "###" + "#.." + "#..",
        'C' to "###" + "#.." + "#.." + "#.." + "###",
        'K' to "#.#" + "#.#" + "##." + "#.#" + "#.#",
        'L' to "#.." + "#.." + "#.." + "#.." + "###",
        'G' to "###" + "#.." + "#.#" + "#.#" + "###",
        'B' to "##." + "#.#" + "##." + "#.#" + "##.",
        'Y' to "#.#" + "#.#" + ".#." + ".#." + ".#.",
        'V' to "#.#" + "#.#" + "#.#" + "#.#" + ".#.",
        'X' to "#.#" + "#.#" + ".#." + "#.#" + "#.#",
        'J' to "..#" + "..#" + "..#" + "#.#" + "###",
        'Q' to "###" + "#.#" + "#.#" + "###" + "..#",
        'Z' to "###" + "..#" + ".#." + "#.." + "###",
    )

    fun supports(c: Char) = glyphs.containsKey(c.uppercaseChar())

    /** Row-major W*H bits, unknown chars render blank. */
    fun bits(c: Char): BooleanArray {
        val g = glyphs[c.uppercaseChar()] ?: glyphs.getValue(' ')
        return BooleanArray(W * H) { g[it] == '#' }
    }

    fun width(text: String): Int = if (text.isEmpty()) 0 else text.length * (W + 1) - 1
}
